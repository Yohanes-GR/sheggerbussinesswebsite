export function SocialLinks({
  company,
  light = false,
  compact = false,
  include,
}: {
  company: Company;
  light?: boolean;
  compact?: boolean;
  include?: string[];
}) {
  const items = socialNetworks(company).filter(
    (item) => !include || include.includes(item.key),
  );
  if (!items.length) return null;

  return (
    <ul className={`flex flex-wrap items-center ${compact ? "gap-2" : "gap-3"}`}>
      {items.map((item) => {
        const tone = light
          ? "border-white/20 text-white"
          : "border-black/10 text-brand";
        const icon = (
          <svg viewBox="0 0 24 24" className="h-4 w-4 fill-current" aria-hidden>
            {icons[item.key]}
          </svg>
        );

        return (
          <li key={item.key}>
            {item.href ? (
              <a
                href={item.href}
                target="_blank"
                rel="noreferrer"
                aria-label={item.label}
                className={`inline-flex h-10 w-10 items-center justify-center rounded-full border transition hover:border-accent hover:bg-accent hover:text-white ${tone}`}
              >
                {icon}
              </a>
            ) : (
              <span
                aria-label={`${item.label} (coming soon)`}
                title={`${item.label} coming soon`}
                className={`inline-flex h-10 w-10 cursor-default items-center justify-center rounded-full border opacity-70 ${tone}`}
              >
                {icon}
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}
